func ptr(s string) *string { return &s }

func orderDesign() sqldialect.TableDesign {
	return sqldialect.TableDesign{
		Columns: []sqldialect.ColumnSpec{
			{Name: "id", TypeName: "integer", Identity: true},
			{Name: "customer_id", TypeName: "integer"},
			{Name: "note", TypeName: "varchar(100)", Nullable: true, Default: ptr("'none'"), Collation: ptr("nocase")},
		},
		PrimaryKeyName: "pk_orders",
		PrimaryKey:     []string{"id"},
		Uniques:        []sqldialect.UniqueSpec{{Name: "uq_note", Columns: []string{"note"}}},
		Checks:         []sqldialect.CheckSpec{{Name: "ck_customer", Expression: "customer_id > 0"}},
		ForeignKeys: []sqldialect.ForeignKeySpec{{
			Name: "fk_customer", Columns: []string{"customer_id"}, RefTable: "customers", RefColumns: []string{"id"},
			OnDelete: engine.ReferentialCascade, OnUpdate: engine.ReferentialNoAction,
		}},
		Indexes: []engine.IndexSpec{{Name: "ix_orders_customer", Keys: []engine.IndexKey{{Name: "customer_id"}}}},
	}
}

func TestCreateTableGolden(t *testing.T) {
	design := orderDesign()
	cases := []struct {
		name    string
		d       sqldialect.Dialect
		collate string
		want    []string
	}{
		{"postgres", sqldialect.Postgres, `"nocase"`, []string{
			"CREATE TABLE \"app\".\"orders\" (\n  \"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  \"customer_id\" integer NOT NULL,\n  \"note\" varchar(100) COLLATE \"nocase\" DEFAULT 'none',\n  CONSTRAINT \"pk_orders\" PRIMARY KEY (\"id\"),\n  CONSTRAINT \"uq_note\" UNIQUE (\"note\"),\n  CONSTRAINT \"ck_customer\" CHECK (customer_id > 0),\n  CONSTRAINT \"fk_customer\" FOREIGN KEY (\"customer_id\") REFERENCES \"app\".\"customers\" (\"id\") ON DELETE CASCADE ON UPDATE NO ACTION\n);",
			"CREATE INDEX \"ix_orders_customer\" ON \"app\".\"orders\" (\"customer_id\");",
		}},
		{"mysql", sqldialect.MySQL, "nocase", []string{
			"CREATE TABLE `app`.`orders` (\n  `id` integer AUTO_INCREMENT NOT NULL,\n  `customer_id` integer NOT NULL,\n  `note` varchar(100) COLLATE nocase DEFAULT 'none',\n  PRIMARY KEY (`id`),\n  CONSTRAINT `uq_note` UNIQUE (`note`),\n  CONSTRAINT `ck_customer` CHECK (customer_id > 0),\n  CONSTRAINT `fk_customer` FOREIGN KEY (`customer_id`) REFERENCES `app`.`customers` (`id`) ON DELETE CASCADE ON UPDATE NO ACTION\n);",
			"CREATE INDEX `ix_orders_customer` ON `app`.`orders` (`customer_id`);",
		}},
		{"mssql", sqldialect.MSSQL, "nocase", []string{
			"CREATE TABLE [app].[orders] (\n  [id] integer IDENTITY(1,1) NOT NULL,\n  [customer_id] integer NOT NULL,\n  [note] varchar(100) COLLATE nocase NULL DEFAULT 'none',\n  CONSTRAINT [pk_orders] PRIMARY KEY ([id]),\n  CONSTRAINT [uq_note] UNIQUE ([note]),\n  CONSTRAINT [ck_customer] CHECK (customer_id > 0),\n  CONSTRAINT [fk_customer] FOREIGN KEY ([customer_id]) REFERENCES [app].[customers] ([id]) ON DELETE CASCADE ON UPDATE NO ACTION\n);",
			"CREATE INDEX [ix_orders_customer] ON [app].[orders] ([customer_id]);",
		}},
		{"sqlite", sqldialect.SQLite, "nocase", []string{
			"CREATE TABLE \"app\".\"orders\" (\n  \"id\" INTEGER PRIMARY KEY AUTOINCREMENT,\n  \"customer_id\" integer NOT NULL,\n  \"note\" varchar(100) COLLATE nocase DEFAULT 'none',\n  CONSTRAINT \"uq_note\" UNIQUE (\"note\"),\n  CONSTRAINT \"ck_customer\" CHECK (customer_id > 0),\n  CONSTRAINT \"fk_customer\" FOREIGN KEY (\"customer_id\") REFERENCES \"app\".\"customers\" (\"id\") ON DELETE CASCADE ON UPDATE NO ACTION\n);",
			"CREATE INDEX \"app\".\"ix_orders_customer\" ON \"orders\" (\"customer_id\");",
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			d := design
			d.Columns = append([]sqldialect.ColumnSpec(nil), design.Columns...)
			d.Columns[2].Collation = ptr(strings.Trim(tc.collate, `"`))
			script, err := sqldialect.BuildDDL(tc.d, sqldialect.Target{Schema: "app", Table: "orders"}, nil, []sqldialect.Change{sqldialect.CreateTable{Design: d}})
			if err != nil {
				t.Fatal(err)
			}
			var got []string
			for _, s := range script.Statements {
				got = append(got, s.SQL)
				if s.Destructive {
					t.Errorf("%q is marked destructive", s.Summary)
				}
			}
			if strings.Join(got, "\n") != strings.Join(tc.want, "\n") {
				t.Errorf("statements:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(tc.want, "\n"))
			}
			if len(script.Warnings) != map[bool]int{true: 1, false: 0}[tc.name == "mysql"] {
				t.Errorf("warnings = %v", script.Warnings)
			}
		})
	}
}

func TestAlterGolden(t *testing.T) {
	name := func(n string) sqldialect.ColumnSpec {
		return sqldialect.ColumnSpec{Name: n, TypeName: "varchar(50)", Nullable: true}
	}
	wider := name("title")
	wider.TypeName = "varchar(200)"
	wider.Nullable = false
	wider.Default = ptr("'x'")
	cases := []struct {
		name   string
		d      sqldialect.Dialect
		change sqldialect.Change
		want   []string
		bad    []bool
	}{
		{"postgres add column", sqldialect.Postgres, sqldialect.AddColumn{Column: name("email")}, []string{`ALTER TABLE "app"."t" ADD COLUMN "email" varchar(50);`}, nil},
		{"mysql add column", sqldialect.MySQL, sqldialect.AddColumn{Column: name("email")}, []string{"ALTER TABLE `app`.`t` ADD COLUMN `email` varchar(50);"}, nil},
		{"mssql add column", sqldialect.MSSQL, sqldialect.AddColumn{Column: name("email")}, []string{"ALTER TABLE [app].[t] ADD [email] varchar(50) NULL;"}, nil},
		{"sqlite add column", sqldialect.SQLite, sqldialect.AddColumn{Column: name("email")}, []string{`ALTER TABLE "app"."t" ADD COLUMN "email" varchar(50);`}, nil},
		{"postgres drop column", sqldialect.Postgres, sqldialect.DropColumn{Name: "old"}, []string{`ALTER TABLE "app"."t" DROP COLUMN "old";`}, []bool{true}},
		{"postgres rename column", sqldialect.Postgres, sqldialect.RenameColumn{From: "a", To: "b"}, []string{`ALTER TABLE "app"."t" RENAME COLUMN "a" TO "b";`}, nil},
		{"mssql rename column", sqldialect.MSSQL, sqldialect.RenameColumn{From: "a", To: "b"}, []string{"EXEC sp_rename N'[app].[t].[a]', N'b', N'COLUMN';"}, nil},
		{"postgres rename table", sqldialect.Postgres, sqldialect.RenameTable{NewName: "u"}, []string{`ALTER TABLE "app"."t" RENAME TO "u";`}, nil},
		{"mssql rename table", sqldialect.MSSQL, sqldialect.RenameTable{NewName: "u"}, []string{"EXEC sp_rename N'[app].[t]', N'u';"}, nil},
		{"postgres drop table", sqldialect.Postgres, sqldialect.DropTable{}, []string{`DROP TABLE "app"."t";`}, []bool{true}},
		{"postgres alter column", sqldialect.Postgres, sqldialect.AlterColumn{Before: name("title"), After: wider}, []string{
			`ALTER TABLE "app"."t" ALTER COLUMN "title" TYPE varchar(200);`,
			`ALTER TABLE "app"."t" ALTER COLUMN "title" SET NOT NULL;`,
			`ALTER TABLE "app"."t" ALTER COLUMN "title" SET DEFAULT 'x';`,
		}, []bool{true, false, false}},
		{"mysql alter column", sqldialect.MySQL, sqldialect.AlterColumn{Before: name("title"), After: wider}, []string{
			"ALTER TABLE `app`.`t` MODIFY COLUMN `title` varchar(200) NOT NULL DEFAULT 'x';",
		}, []bool{true}},
		{"mssql alter column", sqldialect.MSSQL, sqldialect.AlterColumn{Before: name("title"), After: func() sqldialect.ColumnSpec { c := wider; c.Default = nil; return c }()}, []string{
			"ALTER TABLE [app].[t] ALTER COLUMN [title] varchar(200) NOT NULL;",
		}, []bool{true}},
		{"postgres add fk", sqldialect.Postgres, sqldialect.AddForeignKey{ForeignKey: sqldialect.ForeignKeySpec{Name: "fk", Columns: []string{"a"}, RefSchema: "other", RefTable: "r", RefColumns: []string{"id"}, OnDelete: engine.ReferentialSetNull}}, []string{
			`ALTER TABLE "app"."t" ADD CONSTRAINT "fk" FOREIGN KEY ("a") REFERENCES "other"."r" ("id") ON DELETE SET NULL;`,
		}, nil},
		{"postgres add unique", sqldialect.Postgres, sqldialect.AddUnique{Unique: sqldialect.UniqueSpec{Columns: []string{"a", "b"}}}, []string{`ALTER TABLE "app"."t" ADD UNIQUE ("a", "b");`}, nil},
		{"postgres drop constraint", sqldialect.Postgres, sqldialect.DropConstraint{Name: "fk"}, []string{`ALTER TABLE "app"."t" DROP CONSTRAINT "fk";`}, []bool{true}},
		{"mysql drop constraint unknown kind", sqldialect.MySQL, sqldialect.DropConstraint{Name: "ck"}, []string{"ALTER TABLE `app`.`t` DROP CONSTRAINT `ck`;"}, []bool{true}},
		{"mysql drop index", sqldialect.MySQL, sqldialect.DropIndex{Name: "ix"}, []string{"DROP INDEX `ix` ON `app`.`t`;"}, []bool{true}},
		{"postgres add index", sqldialect.Postgres, sqldialect.AddIndex{Index: engine.IndexSpec{Name: "ix", Keys: []engine.IndexKey{{Name: "a"}}}}, []string{`CREATE INDEX "ix" ON "app"."t" ("a");`}, nil},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			script, err := sqldialect.BuildDDL(tc.d, sqldialect.Target{Schema: "app", Table: "t"}, nil, []sqldialect.Change{tc.change})
			if err != nil {
				t.Fatal(err)
			}
			for i, s := range script.Statements {
				if i >= len(tc.want) || s.SQL != tc.want[i] {
					t.Errorf("statement %d = %q, want %q", i, s.SQL, tc.want)
				}
				wantBad := i < len(tc.bad) && tc.bad[i]
				if s.Destructive != wantBad {
					t.Errorf("statement %d destructive = %v, want %v", i, s.Destructive, wantBad)
				}
			}
			if len(script.Statements) != len(tc.want) {
				t.Errorf("got %d statements, want %d", len(script.Statements), len(tc.want))
			}
		})
	}
}

func TestMySQLDropConstraintUsesTheKindFromTheCurrentTable(t *testing.T) {
	current := &engine.TableDetails{
		ForeignKeys: []engine.ForeignKeyDef{{Name: "fk_a"}},
		Indexes:     []engine.IndexDef{{Name: "uq_b", IsUnique: true}},
	}
	for name, want := range map[string]string{
		"fk_a": "ALTER TABLE `t` DROP FOREIGN KEY `fk_a`;",
		"uq_b": "ALTER TABLE `t` DROP INDEX `uq_b`;",
	} {
		script, err := sqldialect.BuildDDL(sqldialect.MySQL, sqldialect.Target{Table: "t"}, current, []sqldialect.Change{sqldialect.DropConstraint{Name: name}})
		if err != nil || script.Statements[0].SQL != want {
			t.Errorf("%s: %v %+v, want %s", name, err, script.Statements, want)
		}
	}
}

func TestChangesAfterRenameUseTheNewName(t *testing.T) {
	script, err := sqldialect.BuildDDL(sqldialect.Postgres, sqldialect.Target{Table: "t"}, nil, []sqldialect.Change{
		sqldialect.RenameTable{NewName: "u"}, sqldialect.DropColumn{Name: "c"},
	})
	if err != nil || script.Statements[1].SQL != `ALTER TABLE "u" DROP COLUMN "c";` {
		t.Errorf("%v %+v", err, script.Statements)
	}
}

func TestUnsupportedAndInvalidChanges(t *testing.T) {
	col := sqldialect.ColumnSpec{Name: "a", TypeName: "int"}
	other := sqldialect.ColumnSpec{Name: "a", TypeName: "bigint"}
	cases := []struct {
		name        string
		d           sqldialect.Dialect
		change      sqldialect.Change
		unsupported bool
	}{
		{"sqlite alter column", sqldialect.SQLite, sqldialect.AlterColumn{Before: col, After: other}, true},
		{"sqlite add foreign key", sqldialect.SQLite, sqldialect.AddForeignKey{ForeignKey: sqldialect.ForeignKeySpec{Columns: []string{"a"}, RefTable: "r", RefColumns: []string{"id"}}}, true},
		{"sqlite drop constraint", sqldialect.SQLite, sqldialect.DropConstraint{Name: "x"}, true},
		{"mssql restrict", sqldialect.MSSQL, sqldialect.AddForeignKey{ForeignKey: sqldialect.ForeignKeySpec{Columns: []string{"a"}, RefTable: "r", RefColumns: []string{"id"}, OnDelete: engine.ReferentialRestrict}}, true},
		{"mysql set default", sqldialect.MySQL, sqldialect.AddForeignKey{ForeignKey: sqldialect.ForeignKeySpec{Columns: []string{"a"}, RefTable: "r", RefColumns: []string{"id"}, OnUpdate: engine.ReferentialSetDefault}}, true},
		{"mssql default change", sqldialect.MSSQL, sqldialect.AlterColumn{Before: col, After: sqldialect.ColumnSpec{Name: "a", TypeName: "int", Default: ptr("1")}}, true},
		{"postgres identity change", sqldialect.Postgres, sqldialect.AlterColumn{Before: col, After: sqldialect.ColumnSpec{Name: "a", TypeName: "int", Identity: true}}, true},
		{"alter without differences", sqldialect.Postgres, sqldialect.AlterColumn{Before: col, After: col}, false},
		{"table without columns", sqldialect.Postgres, sqldialect.CreateTable{}, false},
		{"collation with a quote", sqldialect.Postgres, sqldialect.AddColumn{Column: sqldialect.ColumnSpec{Name: "a", TypeName: "text", Collation: ptr(`x"; DROP TABLE t; --`)}}, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := sqldialect.BuildDDL(tc.d, sqldialect.Target{Table: "t"}, nil, []sqldialect.Change{tc.change})
			if err == nil {
				t.Fatal("expected an error")
			}
			var u *sqldialect.UnsupportedError
			if errors.As(err, &u) != tc.unsupported {
				t.Errorf("error = %v, unsupported = %v", err, tc.unsupported)
			}
		})
	}
}

