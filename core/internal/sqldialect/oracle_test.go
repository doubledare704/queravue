func TestOracleDialect(t *testing.T) {
	d := Oracle
	if got := d.QuoteIdent(`a"b`); got != `"a""b"` {
		t.Errorf("QuoteIdent = %s", got)
	}
	if got := d.QualifyTableIn("ignored", "HR", "emp"); got != `"HR"."emp"` {
		t.Errorf("QualifyTableIn = %s", got)
	}
	if got := d.Placeholder(3); got != ":3" {
		t.Errorf("Placeholder = %s", got)
	}
	if got := d.OrderTerm(`"a"`, true, NullsLast); got != `"a" DESC NULLS LAST` {
		t.Errorf("OrderTerm = %s", got)
	}
	sql, stable := d.Paginate(`SELECT * FROM "t"`, 50, false)
	if sql != `SELECT * FROM "t" FETCH FIRST 50 ROWS ONLY` || !stable {
		t.Errorf("Paginate = %q, %v", sql, stable)
	}
	if sql, _ := d.Paginate("SELECT 1 FROM dual", 0, false); sql != "SELECT 1 FROM dual" {
		t.Errorf("Paginate without a limit = %q", sql)
	}
}

func TestOracleLiterals(t *testing.T) {
	d := Oracle
	when := time.Date(2026, 1, 2, 3, 4, 5, 0, time.FixedZone("", 7200))
	for _, tt := range []struct {
		v    engine.Value
		want string
	}{
		{engine.Bool(true), "1"},
		{engine.Text("it's"), "'it''s'"},
		{engine.Timestamptz(when), "TIMESTAMP '2026-01-02 03:04:05 +02:00'"},
		{engine.Bytes([]byte{0, 255}), "HEXTORAW('00FF')"},
		{engine.Null(), "NULL"},
		{engine.Decimal("1.5"), "1.5"},
	} {
		if got := d.FormatLiteral(tt.v); got != tt.want {
			t.Errorf("FormatLiteral = %s, want %s", got, tt.want)
		}
	}
}

func TestOracleIndexes(t *testing.T) {
	sql, warnings, err := Oracle.CreateIndex("", "HR", "emp", engine.IndexSpec{
		Name: "ix", Unique: true, Keys: []engine.IndexKey{{Name: "a"}, {Name: "b", Kind: engine.IndexKeyDescending}},
		Options: map[string]string{OptionOnline: "true"},
	})
	if err != nil {
		t.Fatal(err)
	}
	if want := `CREATE UNIQUE INDEX "ix" ON "HR"."emp" ("a", "b" DESC) ONLINE;`; sql != want {
		t.Errorf("sql = %s, want %s", sql, want)
	}
	if len(warnings) != 1 {
		t.Errorf("warnings = %v", warnings)
	}
	if _, _, err := Oracle.CreateIndex("", "HR", "emp", engine.IndexSpec{Keys: []engine.IndexKey{{Name: "a"}}, PartialPredicate: "a > 1"}); err == nil {
		t.Error("a partial index must be refused")
	}
	if got := Oracle.DropIndex("", "HR", "emp", "ix"); got != `DROP INDEX "HR"."ix";` {
		t.Errorf("DropIndex = %s", got)
	}
}

func oracleScript(t *testing.T, current *engine.TableDetails, changes ...Change) Script {
	t.Helper()
	script, err := BuildDDL(Oracle, Target{Schema: "HR", Table: "emp"}, current, changes)
	if err != nil {
		t.Fatal(err)
	}
	return script
}

func TestOracleDDLCreateTable(t *testing.T) {
	def := "0"
	script := oracleScript(t, nil, CreateTable{Design: TableDesign{
		Columns: []ColumnSpec{
			{Name: "id", TypeName: "NUMBER(10)", Identity: true},
			{Name: "name", TypeName: "VARCHAR2(50)", Nullable: true},
			{Name: "n", TypeName: "NUMBER(5)", Default: &def},
		},
		PrimaryKey:  []string{"id"},
		ForeignKeys: []ForeignKeySpec{{Name: "fk", Columns: []string{"n"}, RefTable: "other", RefColumns: []string{"id"}, OnDelete: engine.ReferentialCascade, OnUpdate: engine.ReferentialNoAction}},
	}})
	if script.Transactional {
		t.Error("Oracle DDL commits implicitly, so the script is not transactional")
	}
	if len(script.Warnings) == 0 {
		t.Error("expected the implicit-commit warning")
	}
	sql := script.Statements[0].SQL
	for _, want := range []string{
		`"id" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL`,
		`"name" VARCHAR2(50)`,
		`"n" NUMBER(5) DEFAULT 0 NOT NULL`,
		`PRIMARY KEY ("id")`,
		`CONSTRAINT "fk" FOREIGN KEY ("n") REFERENCES "HR"."other" ("id") ON DELETE CASCADE`,
	} {
		if !strings.Contains(sql, want) {
			t.Errorf("CREATE TABLE lacks %q:\n%s", want, sql)
		}
	}
	if strings.Contains(sql, "ON UPDATE") {
		t.Errorf("Oracle has no ON UPDATE:\n%s", sql)
	}
}

func TestOracleDDLAlterAndRename(t *testing.T) {
	old, newDefault := "1", "2"
	script := oracleScript(t, nil,
		AddColumn{Column: ColumnSpec{Name: "extra", TypeName: "VARCHAR2(20)", Nullable: true}},
		RenameColumn{From: "extra", To: "more"},
		AlterColumn{
			Before: ColumnSpec{Name: "more", TypeName: "VARCHAR2(20)", Nullable: true, Default: &old},
			After:  ColumnSpec{Name: "more", TypeName: "VARCHAR2(80)", Nullable: false, Default: &newDefault},
		},
		AlterColumn{
			Before: ColumnSpec{Name: "more", TypeName: "VARCHAR2(80)", Nullable: false, Default: &newDefault},
			After:  ColumnSpec{Name: "more", TypeName: "VARCHAR2(80)", Nullable: false},
		},
		DropColumn{Name: "more"},
		DropConstraint{Name: "fk"},
		RenameTable{NewName: "staff"},
	)
	want := []string{
		`ALTER TABLE "HR"."emp" ADD "extra" VARCHAR2(20);`,
		`ALTER TABLE "HR"."emp" RENAME COLUMN "extra" TO "more";`,
		`ALTER TABLE "HR"."emp" MODIFY ("more" VARCHAR2(80) DEFAULT 2 NOT NULL);`,
		`ALTER TABLE "HR"."emp" MODIFY ("more" DEFAULT NULL);`,
		`ALTER TABLE "HR"."emp" DROP COLUMN "more";`,
		`ALTER TABLE "HR"."emp" DROP CONSTRAINT "fk";`,
		`ALTER TABLE "HR"."emp" RENAME TO "staff";`,
	}
	if len(script.Statements) != len(want) {
		t.Fatalf("got %d statements, want %d: %+v", len(script.Statements), len(want), script.Statements)
	}
	for i, w := range want {
		if script.Statements[i].SQL != w {
			t.Errorf("statement %d = %s, want %s", i, script.Statements[i].SQL, w)
		}
	}
}

func TestOracleDDLRefusals(t *testing.T) {
	for name, change := range map[string]Change{
		"restrict":          AddForeignKey{ForeignKey: ForeignKeySpec{Columns: []string{"a"}, RefTable: "o", RefColumns: []string{"id"}, OnDelete: engine.ReferentialRestrict}},
		"on update cascade": AddForeignKey{ForeignKey: ForeignKeySpec{Columns: []string{"a"}, RefTable: "o", RefColumns: []string{"id"}, OnUpdate: engine.ReferentialCascade}},
		"identity switch":   AlterColumn{Before: ColumnSpec{Name: "a", TypeName: "NUMBER"}, After: ColumnSpec{Name: "a", TypeName: "NUMBER", Identity: true}},
	} {
		_, err := BuildDDL(Oracle, Target{Schema: "HR", Table: "emp"}, nil, []Change{change})
		var unsupported *UnsupportedError
		if err == nil || !asUnsupported(err, &unsupported) {
			t.Errorf("%s: err = %v, want an unsupported error", name, err)
		}
	}
}

func asUnsupported(err error, target **UnsupportedError) bool {
	u, ok := err.(*UnsupportedError) //nolint:errorlint // BuildDDL returns it unwrapped
	*target = u
	return ok
}
