func keywordsOf(d sqlsplit.Dialect) []string  { return keywordsByDialect[d] }
func functionsOf(d sqlsplit.Dialect) []string { return functionsByDialect[d] }
func reservedWords(d sqlsplit.Dialect) map[string]bool {
	return reservedByDialect[d]
}
