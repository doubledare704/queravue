var (
	keywordsByDialect  = map[sqlsplit.Dialect][]string{}
	functionsByDialect = map[sqlsplit.Dialect][]string{}
	reservedByDialect  = map[sqlsplit.Dialect]map[string]bool{}
)

func init() {
	for _, d := range []sqlsplit.Dialect{sqlsplit.Postgres, sqlsplit.MySQL, sqlsplit.MSSQL, sqlsplit.Oracle, sqlsplit.SQLite} {
		keywordsByDialect[d] = words(commonKeywords + " " + dialectKeywords[d])
		functionsByDialect[d] = words(commonFunctions + " " + dialectFunctions[d])
		set := map[string]bool{}
		for _, w := range strings.Fields(commonReserved + " " + dialectReserved[d]) {
			set[w] = true
		}
		reservedByDialect[d] = set
	}
}

// words splits a list into unique entries, in order. An underscore inside a
// keyword entry written as A_B stands for the two-word keyword "A B", except
// for names that really contain one (AUTO_INCREMENT and the like).
func words(list string) []string {
	seen := map[string]bool{}
	var out []string
	for _, w := range strings.Fields(list) {
		if multiWordKeywords[w] {
			w = strings.ReplaceAll(w, "_", " ")
		}
		if !seen[w] {
			seen[w] = true
			out = append(out, w)
		}
	}
	return out
}

